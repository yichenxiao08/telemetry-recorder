// perfreport generates comparison tables from retained machine measurements.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

func generate(directory, out string) error {
	var b strings.Builder
	fmt.Fprintln(&b, "# Performance measurements\n\nGenerated by `go run ./scripts/perfreport`; rates are committed records/second. Separate rates are diagnostics, not simultaneous acceptance. Every seed must meet its target.\n\n## Throughput\n\n| Measurement | Signal | Minimum /s | Median /s | Target /s | Every seed met |\n|---|---|---:|---:|---:|---|")
	paths, err := filepath.Glob(filepath.Join(directory, "perf-*-summary.json"))
	if err != nil {
		return err
	}
	slices.Sort(paths)
	for _, path := range paths {
		var r struct {
			Signals map[string]struct {
				Minimum, Median, Target float64
				Met                     bool `json:"all_trials_met_target"`
			} `json:"signals"`
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if err = json.Unmarshal(data, &r); err != nil {
			return err
		}
		for _, kind := range []string{"span", "log", "metric"} {
			s, ok := r.Signals[kind]
			if !ok {
				return fmt.Errorf("%s: missing %s summary", path, kind)
			}
			fmt.Fprintf(&b, "| %s | %s | %.0f | %.0f | %.0f | %v |\n", filepath.Base(path), kind, s.Minimum, s.Median, s.Target, s.Met)
		}
	}
	fmt.Fprintln(&b, "\n## Startup\n\nOpen only; copy, count/audit and Close excluded. Timeouts are failed, censored observations.\n\n| Measurement | Open seconds | Close seconds | Error |\n|---|---:|---:|---|")
	paths, err = filepath.Glob(filepath.Join(directory, "perf-*-startup*.json"))
	if err != nil {
		return err
	}
	slices.Sort(paths)
	for _, path := range paths {
		var r struct {
			Seconds float64 `json:"startup_seconds"`
			Close   float64 `json:"close_seconds"`
			Error   string  `json:"error"`
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if err = json.Unmarshal(data, &r); err != nil {
			return err
		}
		message := strings.ReplaceAll(strings.ReplaceAll(r.Error, "|", `\|`), "\n", " ")
		fmt.Fprintf(&b, "| %s | %.6f | %.6f | %s |\n", filepath.Base(path), r.Seconds, r.Close, message)
	}
	fmt.Fprintln(&b, "\n## Million-record fixture\n\nFile bytes include free pages. Live bytes subtract the measured freelist; no records were dropped. Logical view rows are not materialized rows. Queries require time bounds and LIMIT 100; five repeats include a new SQLite connection/page cache for each first query, with OS caches unflushed.\n\n| Measurement | File bytes | Live bytes | Physical scopes | Logical links | Logical provenance |\n|---|---:|---:|---:|---:|---:|")
	paths, err = filepath.Glob(filepath.Join(directory, "perf-*-million*.json"))
	if err != nil {
		return err
	}
	slices.Sort(paths)
	type query struct {
		Name   string    `json:"name"`
		Values []float64 `json:"milliseconds"`
		Met    bool      `json:"all_under_500ms"`
	}
	type fixture struct {
		Bytes    int64            `json:"database_bytes"`
		PageSize int64            `json:"page_size"`
		Free     int64            `json:"free_pages"`
		Counts   map[string]int64 `json:"counts"`
		Queries  []query          `json:"queries"`
	}
	fixtures := map[string]fixture{}
	for _, path := range paths {
		var r fixture
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if err = json.Unmarshal(data, &r); err != nil {
			return err
		}
		fixtures[path] = r
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d |\n", filepath.Base(path), r.Bytes, r.Bytes-r.PageSize*r.Free, r.Counts["context_scopes"], r.Counts["context_links"], r.Counts["context_matches"])
	}
	fmt.Fprintln(&b, "\n| Measurement | Query | First ms | Median ms | Maximum ms | Every repeat <500 ms |\n|---|---|---:|---:|---:|---|")
	for _, path := range paths {
		for _, q := range fixtures[path].Queries {
			if len(q.Values) != 5 {
				return fmt.Errorf("%s: expected five query repeats", path)
			}
			ordered := slices.Clone(q.Values)
			slices.Sort(ordered)
			fmt.Fprintf(&b, "| %s | %s | %.3f | %.3f | %.3f | %v |\n", filepath.Base(path), q.Name, q.Values[0], ordered[2], ordered[4], q.Met)
		}
	}
	if err = os.WriteFile(out, []byte(b.String()), 0644); err != nil {
		return err
	}
	fmt.Print(b.String())
	return nil
}

func main() {
	directory := flag.String("results", "benchmark/results", "Input directory")
	out := flag.String("out", "benchmark/results/performance-summary.md", "Generated Markdown path")
	flag.Parse()
	if err := generate(*directory, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
