// m4breport generates tables from retained measurements; it never edits ranks.
package main

import (
	"encoding/json"
	"fmt"
	"github.com/signalscout/signalscout/internal/model"
	"os"
	"strings"
)

func load(path string, value any) error {
	data, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	return json.Unmarshal(data, value)
}
func rank(ds []model.Difference, kind, name string) int {
	for i, d := range ds {
		if d.Type == kind && d.Name == name {
			return i + 1
		}
	}
	return 0
}
func rankText(n int) string {
	if n == 0 {
		return "absent"
	}
	return fmt.Sprint(n)
}
func maximum(xs []float64) float64 {
	n := 0.0
	for _, x := range xs {
		n = max(n, x)
	}
	return n
}
func run() error {
	var b strings.Builder
	b.WriteString("# M4b measurements\n\nGenerated by `go run ./scripts/m4breport`. Original 5k/5k/10k misses remain in docs/performance.md. Targets were changed by the owner, not met retrospectively. Pipeline is an estimate.\n\n## Saved workload rates\n\nPeak means count in a sliding one-second window; averages use actual phase length. Event-time rates do not measure exporter bursts.\n\n| Seed | Phase | Seconds | Average spans/logs/points per sec | Peak spans/logs/points |\n|---|---|---:|---|---|\n")
	var workload struct {
		Phases []struct {
			Seed    int
			Phase   string
			Start   int64              `json:"start_ns"`
			End     int64              `json:"end_ns"`
			Average map[string]float64 `json:"average_per_second"`
			Peak    map[string]int     `json:"peak_sliding_one_second"`
		}
	}
	if err := load("benchmark/results/m4b-workload-rates.json", &workload); err != nil {
		return err
	}
	for _, p := range workload.Phases {
		fmt.Fprintf(&b, "| %d | %s | %.3f | %.1f / %.1f / %.1f | %d / %d / %d |\n", p.Seed, p.Phase, float64(p.End-p.Start)/1e9, p.Average["span"], p.Average["log"], p.Average["metric"], p.Peak["span"], p.Peak["log"], p.Peak["metric"])
	}
	var profiles []struct {
		Profile struct {
			Name    string
			Targets map[string]int
		}
		Measurements []struct {
			Seed  int
			Rates map[string]float64 `json:"per_second"`
			Met   bool               `json:"all_targets_met"`
		}
	}
	if err := load("benchmark/results/m4b-combined-profiles.json", &profiles); err != nil {
		return err
	}
	b.WriteString("\n## Revised combined profiles\n\n30-second windows, serve defaults, seeds 1–5. Pass requires every intended record before the deadline; final drain remains in reported rates.\n\n| Profile | Targets spans/logs/points per sec | Seed | Measured spans/logs/points per sec | Pass |\n|---|---|---:|---|---|\n")
	for _, p := range profiles {
		for _, m := range p.Measurements {
			fmt.Fprintf(&b, "| %s | %d / %d / %d | %d | %.2f / %.2f / %.2f | %v |\n", p.Profile.Name, p.Profile.Targets["span"], p.Profile.Targets["log"], p.Profile.Targets["metric"], m.Seed, m.Rates["span"], m.Rates["log"], m.Rates["metric"], m.Met)
		}
	}
	var demos []struct {
		Seed           int
		Representative string
		TraceLogs      int
		Trials         []struct {
			RunID, Mode string
			ElapsedMS   float64
			Result      model.DiffResult
		}
		ServiceStats []struct{ Requests, Errors int }
	}
	if err := load("benchmark/results/m4b-context-demo-final.json", &demos); err != nil {
		return err
	}
	b.WriteString("\n## Saved-demo ranks\n\nAll nine failures per seed, both baseline modes; no scoring constants changed for these data. Absent is not a successful detection. Seed 1's in-use sampler recorded only zero; its missing detection is an explicit owner-delegated data-limited acceptance exception.\n\n| Seed | Run | Mode | In-use metric | Capacity metric | Acquire latency | Cache event decoy | Total read/compute/save ms |\n|---|---|---|---|---|---|---|---:|\n")
	for _, d := range demos {
		for _, t := range d.Trials {
			ds := t.Result.Differences
			fmt.Fprintf(&b, "| %d | %s | %s | %s | %s | %s | %s | %.2f |\n", d.Seed, t.RunID, t.Mode, rankText(rank(ds, "context_metric", "db.pool.in_use")), rankText(rank(ds, "context_metric", "db.pool.capacity")), rankText(rank(ds, "latency", "db.pool.acquire")), rankText(rank(ds, "presence", "cache.miss")), t.ElapsedMS)
		}
		fmt.Fprintf(&b, "\nSeed %d representative: `%s`; trace log lookup returns %d records.\n", d.Seed, d.Representative, d.TraceLogs)
		for _, t := range d.Trials {
			if t.RunID != d.Representative {
				continue
			}
			fmt.Fprintf(&b, "\n%s top ranks:\n\n", t.Mode)
			for i, x := range t.Result.Differences {
				if i >= 5 {
					break
				}
				fmt.Fprintf(&b, "- %d. %s / %s — %.6f (raw baseline rate %.3f)\n", i+1, x.Type, x.Name, x.Score, x.BaselineRate)
			}
		}
		for _, s := range d.ServiceStats {
			fmt.Fprintf(&b, "\nService overview: %d requests, %d errors in its selected window.\n", s.Requests, s.Errors)
		}
	}
	var queries struct {
		Method  string
		Queries []struct {
			Name string
			MS   []float64 `json:"milliseconds"`
			Rows int
			Met  bool `json:"all_under_500ms"`
		}
	}
	if err := load("benchmark/results/m4b-million-queries-final.json", &queries); err != nil {
		return err
	}
	b.WriteString("\n## Actual explorer API timings over 1M rows\n\n")
	b.WriteString(queries.Method + "\n\n| Query | Rows | Maximum of five (ms) | All under 500 ms |\n|---|---:|---:|---|\n")
	for _, q := range queries.Queries {
		fmt.Fprintf(&b, "| %s | %d | %.4f | %v |\n", q.Name, q.Rows, maximum(q.MS), q.Met)
	}
	return os.WriteFile("benchmark/results/m4b-summary.md", []byte(b.String()), 0644)
}
func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
